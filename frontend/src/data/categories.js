export function unsplashUrl(id, w, q) {
  return (
    'https://images.unsplash.com/photo-' + id +
    '?auto=format&fit=crop&w=' + (w || 900) + '&q=' + (q || 60)
  );
}

/**
 * 1x/2x candidates for a card of `w` CSS pixels. `auto=format` already negotiates AVIF or
 * WebP from the Accept header, so this only has to cover pixel density — the retina
 * variant is requested at a lower quality so the byte cost stays close to the 1x file.
 */
export function unsplashSrcSet(id, w) {
  return unsplashUrl(id, w, 62) + ' 1x, ' + unsplashUrl(id, w * 2, 45) + ' 2x';
}

